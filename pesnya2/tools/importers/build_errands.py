def quoted(text):
    """Имена в «ёлочках» верхнего уровня: «Карта памяти «Скандал»» — одно имя."""
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch == "«":
            if depth > 0:
                cur += ch
            depth += 1
        elif ch == "»":
            depth -= 1
            if depth > 0:
                cur += ch
            elif depth == 0:
                out.append(cur)
                cur = ""
        elif depth > 0:
            cur += ch
    return out


