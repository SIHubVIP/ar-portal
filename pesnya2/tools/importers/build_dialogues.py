def opt(tone, text, nxt="end", fx=None, req=None):
    o = {"tone": tone, "text": text, "next": nxt}
    if fx: o["effects"] = fx
    if req: o["requires"] = req
    return o
def node(spk, text, nxt=None, options=None, fx=None, canon=None):
    n = {"speaker": spk, "text": text}
    if options: n["options"] = options
    else: n["next"] = nxt or "end"
    if fx: n["effects"] = fx
    if canon: n["canon"] = canon
    return n

